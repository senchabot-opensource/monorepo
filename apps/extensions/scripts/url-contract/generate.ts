/**
 * Writes the widget URL golden fixtures (src/__tests__/url-contract/fixtures/*.json) by running the
 * frozen pre-redesign logic in base-reference.ts over a bounded input matrix per widget.
 *
 *   node scripts/url-contract/generate.ts
 *
 * Deterministic: rerunning it must leave the fixtures byte-identical. See README.md.
 */
import { spawnSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as BASE from './base-reference.ts';

const ORIGIN = 'https://extensions.senchabot.com';
const APP_DIR = fileURLToPath(new URL('../../', import.meta.url));
const OUT_DIR = `${APP_DIR}src/__tests__/url-contract/fixtures`;
const ABOUT =
  'Generated by scripts/url-contract/generate.ts from the frozen pre-redesign URL logic ' +
  '(scripts/url-contract/base-reference.ts). Do not edit by hand.';

type Row = Record<string, unknown>;
type Domain = Record<string, readonly unknown[]>;

/**
 * Greedy all-pairs covering array: every value of every parameter meets every value of every
 * other parameter in at least one row. Ties pick the lowest index, so output is deterministic
 * and leans towards the first (default) value.
 */
function allPairs(domain: Domain): Row[] {
  const keys = Object.keys(domain);
  const sizes = keys.map((k) => domain[k].length);
  const id = (i: number, a: number, j: number, b: number) =>
    i < j ? `${i}:${a}|${j}:${b}` : `${j}:${b}|${i}:${a}`;
  const uncovered = new Set<string>();
  for (let i = 0; i < keys.length; i++)
    for (let j = i + 1; j < keys.length; j++)
      for (let a = 0; a < sizes[i]; a++)
        for (let b = 0; b < sizes[j]; b++) uncovered.add(id(i, a, j, b));

  const rows: number[][] = [];
  while (uncovered.size > 0) {
    const [first] = uncovered;
    const [[i, a], [j, b]] = first.split('|').map((p) => p.split(':').map(Number));
    const row = keys.map(() => -1);
    row[i] = a;
    row[j] = b;
    for (let k = 0; k < keys.length; k++) {
      if (row[k] !== -1) continue;
      let best = 0;
      let bestGain = -1;
      for (let v = 0; v < sizes[k]; v++) {
        let gain = 0;
        for (let m = 0; m < keys.length; m++) {
          if (m !== k && row[m] !== -1 && uncovered.has(id(k, v, m, row[m]))) gain++;
        }
        if (gain > bestGain) {
          best = v;
          bestGain = gain;
        }
      }
      row[k] = best;
    }
    for (let m = 0; m < keys.length; m++)
      for (let n = m + 1; n < keys.length; n++) uncovered.delete(id(m, row[m], n, row[n]));
    rows.push(row);
  }
  return rows.map((row) => Object.fromEntries(keys.map((k, i) => [k, domain[k][row[i]]])));
}

/** Only the keys whose value differs from the defaults. */
function overrides<T extends object>(value: T, defaults: T): Partial<T> {
  return Object.fromEntries(
    Object.entries(value).filter(
      ([k, v]) => JSON.stringify(v) !== JSON.stringify(defaults[k as keyof T]),
    ),
  ) as Partial<T>;
}

/** Every non-default value of every key, one key at a time. */
function singleChanges<T extends object>(defaults: T, domain: Domain): Partial<T>[] {
  const out: Partial<T>[] = [];
  for (const [key, values] of Object.entries(domain)) {
    for (const value of values) {
      if (JSON.stringify(value) !== JSON.stringify(defaults[key as keyof T])) {
        out.push({ [key]: value } as Partial<T>);
      }
    }
  }
  return out;
}

const bools = (defaults: object, keys: readonly string[]): Domain =>
  Object.fromEntries(
    keys.map((k) => {
      const d = defaults[k as keyof typeof defaults] as boolean;
      return [k, [d, !d]];
    }),
  );

// Both, one, none, uppercase, padded and whitespace-only. Digit-only names are left out: the
// router parses `?twitch=123` as a number, which the widget routes' schemas reject. Pairwise
// rows lean towards the first entry and skip the empty pair, which never builds a URL.
const CHANNELS: readonly [string, string][] = [
  ['foo', 'bar'],
  ['foo', ''],
  ['', 'bar'],
  ['', ''],
  ['  Foo ', ' BAR  '],
  ['FOO', ''],
  ['   ', 'bar'],
  ['foo', '   '],
  ['streamer_01', 'kick-name'],
];
const PAIR_CHANNELS = CHANNELS.filter(([twitch, kick]) => twitch || kick);

interface Fixture {
  about: string;
  origin: string;
  defaults?: unknown;
  cases: { group: string; input: unknown; expectedUrl: string }[];
}

