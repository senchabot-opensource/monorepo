function obsBridge(): Fixture {
  // Only inputs both versions treat alike. The redesign trims and lowercases channels, trims the
  // WebSocket URL and drops blank or default-equivalent commands on purpose; the tests cover those
  // as named rules and assert that no fixture input falls under them.
  const channels: readonly [string, string][] = [
    ['foo', 'bar'],
    ['foo', ''],
    ['', 'bar'],
    ['streamer_01', 'kick-name'],
  ];
  const users: BASE.CommandUser[][] = [
    [],
    [{ platform: 'twitch', name: 'mod1' }],
    [
      { platform: 'twitch', name: 'a' },
      { platform: 'kick', name: 'b' },
    ],
    [{ platform: 'kick', name: 'x:y' }],
    [{ platform: null, name: 'carol' }],
    [
      { platform: 'twitch', name: 'bob' },
      { platform: null, name: 'carol' },
      { platform: 'kick', name: 'ali' },
    ],
  ];
  const wsUrls = ['', 'ws://192.168.1.5:4455', 'ws://localhost:4455/path?x=1&y=2'];
  const passwords = ['', 'p@ss w&rd=1', ' ', ' padded ', 'ünï+/?%#'];
  // undefined: never typed in (the current form starts empty, the old one started on the default).
  const commandValues = (key: BASE.ObsCommandKey) => [
    undefined,
    '',
    BASE.DEFAULT_OBS_COMMANDS[key],
    `x${key}`,
    `  x${key} `,
    `!My${key.slice(3)}`,
    '!szene ç&=',
  ];
  const keys = Object.keys(BASE.DEFAULT_OBS_COMMANDS) as BASE.ObsCommandKey[];

  const cases: Fixture['cases'] = [];
  const add = (
    group: string,
    [twitch, kick]: readonly string[],
    commandUsers: BASE.CommandUser[],
    commands: Partial<Record<BASE.ObsCommandKey, string>>,
    obsWebsocketUrl: string,
    obsWebsocketPassword: string,
  ) => {
    const defined = Object.fromEntries(
      Object.entries(commands).filter(([, v]) => v !== undefined),
    ) as Partial<Record<BASE.ObsCommandKey, string>>;
    const baseCommands = { ...BASE.DEFAULT_OBS_COMMANDS, ...defined };
    cases.push({
      group,
      input: {
        twitch,
        kick,
        commandUsers,
        commands: defined,
        obsWebsocketUrl,
        obsWebsocketPassword,
      },
      expectedUrl: BASE.baseObsBridgeUrl(ORIGIN, {
        commandUsers,
        obsWebsocketUrl,
        obsWebsocketPassword,
        twitchChannel: twitch,
        kickChannel: kick,
        commands: baseCommands,
      }),
    });
  };

  for (const ch of [...channels, ['', '']]) add('channels', ch, [], {}, '', '');
  for (const key of keys)
    for (const value of commandValues(key).slice(1))
      add('single', ['foo', 'bar'], [], { [key]: value }, '', '');
  for (const row of allPairs({
    channels,
    users,
    wsUrls,
    passwords,
    ...Object.fromEntries(keys.map((k) => [k, commandValues(k)])),
  })) {
    const commands = Object.fromEntries(keys.map((k) => [k, row[k]])) as Partial<
      Record<BASE.ObsCommandKey, string>
    >;
    add(
      'pairwise',
      row.channels as string[],
      row.users as BASE.CommandUser[],
      commands,
      row.wsUrls as string,
      row.passwords as string,
    );
  }
  return { about: ABOUT, origin: ORIGIN, defaults: BASE.DEFAULT_OBS_COMMANDS, cases };
}

