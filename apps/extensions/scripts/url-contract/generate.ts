const fixtures: Record<string, Fixture> = {
  'chat-box': chatBox(),
  'emote-wall': emoteWall(),
  'sub-sprout': subSprout(),
  'obs-bridge': obsBridge(),
};

mkdirSync(OUT_DIR, { recursive: true });
const files: string[] = [];
for (const [name, fixture] of Object.entries(fixtures)) {
  const file = `${OUT_DIR}/${name}.json`;
  writeFileSync(file, JSON.stringify(fixture));
  files.push(file);
  console.log(`${name}: ${fixture.cases.length} cases`);
}
// Biome formats every JSON file under src/; its layout also keeps one case to a few lines.
const biome = spawnSync(`${APP_DIR}node_modules/.bin/biome`, ['format', '--write', ...files], {
  stdio: 'inherit',
});
if (biome.status !== 0) process.exit(biome.status ?? 1);
