function chatBox(): Fixture {
  const D = BASE.DEFAULT_SETTINGS;
  const domain: Domain = {
    platforms: BASE.PLATFORMS,
    platformDisplay: BASE.PLATFORM_DISPLAYS,
    font: BASE.FONTS,
    fontSize: ['18', '', '8', '72', '0', '100', '24'],
    layout: BASE.LAYOUTS,
    orientation: BASE.ORIENTATIONS,
    animation: BASE.ANIMATIONS,
    bgOpacity: ['0.5', '0', '1', '0.3'],
    duration: BASE.DURATIONS,
    highlights: [
      [...BASE.HIGHLIGHTS],
      [],
      ['mention'],
      ['reply', 'mention'],
      ['firstMessage', 'announcement', 'highlighted'],
    ],
    ...bools(D, [
      'background',
      'itemBackground',
      'platformAccent',
      'boldUsernames',
      'boldMessages',
      'sevenTv',
      'bttv',
      'ffz',
      'badges',
      'timestamp',
      'hideBots',
      'hideCommands',
    ]),
  };
  const cases: Fixture['cases'] = [];
  const add = (group: string, settings: BASE.Settings, [twitch, kick]: readonly string[]) =>
    cases.push({
      group,
      input: { twitchChannel: twitch, kickChannel: kick, settings: overrides(settings, D) },
      expectedUrl: BASE.baseChatBoxUrl(ORIGIN, settings, twitch, kick),
    });

  for (const channels of CHANNELS)
    for (const platforms of BASE.PLATFORMS) add('channels', { ...D, platforms }, channels);
  for (const platforms of BASE.PLATFORMS)
    for (const change of singleChanges(D, { ...domain, platforms: [] }))
      add('single', { ...D, platforms, ...change }, ['foo', 'bar']);
  for (const { channels, ...settings } of allPairs({ channels: PAIR_CHANNELS, ...domain }))
    add('pairwise', { ...D, ...(settings as Partial<BASE.Settings>) }, channels as string[]);
  return { about: ABOUT, origin: ORIGIN, defaults: D, cases };
}

